import PptxGenJS from 'pptxgenjs'
import { sanitizeArtifactPayload } from './sanitize'
import type { NormalizedArtifactPayload } from './types'

const COLOR = {
  ink: '20232B',
  muted: '5D6470',
  purple: '5B3FA3',
  light: 'F5F2FB',
  white: 'FFFFFF',
}

function addHeader(slide: PptxGenJS.Slide, payload: NormalizedArtifactPayload, section?: string) {
  slide.background = { color: COLOR.white }
  slide.addText(payload.projectName, { x: 0.6, y: 0.35, w: 8.3, h: 0.3, fontFace: 'Aptos', fontSize: 10, color: COLOR.purple, bold: true, margin: 0 })
  if (section) slide.addText(section, { x: 0.6, y: 0.82, w: 8.3, h: 0.38, fontFace: 'Aptos Display', fontSize: 22, color: COLOR.ink, bold: true, margin: 0 })
}

export async function generatePptx(input: unknown): Promise<Uint8Array> {
  const payload: NormalizedArtifactPayload = sanitizeArtifactPayload(input)
  const presentation = new PptxGenJS()
  presentation.layout = 'LAYOUT_WIDE'
  presentation.author = 'CodeAtlas'
  presentation.company = 'CodeAtlas'
  presentation.subject = `CodeAtlas export for ${payload.projectName}`
  presentation.title = payload.title

  const titleSlide = presentation.addSlide()
  titleSlide.background = { color: COLOR.purple }
  titleSlide.addText(payload.projectName, { x: 0.75, y: 1.25, w: 11.8, h: 0.45, fontFace: 'Aptos', fontSize: 18, color: 'DCD0F7', bold: true, margin: 0 })
  titleSlide.addText(payload.title, { x: 0.75, y: 2.05, w: 11.8, h: 1.1, fontFace: 'Aptos Display', fontSize: 34, color: COLOR.white, bold: true, breakLine: false, margin: 0 })
  titleSlide.addText('Generated by CodeAtlas', { x: 0.75, y: 6.5, w: 5, h: 0.3, fontFace: 'Aptos', fontSize: 11, color: 'DCD0F7', margin: 0 })

  let slide = presentation.addSlide()
  addHeader(slide, payload, 'Overview')
  if (payload.paragraphs.length > 0) {
    slide.addText(payload.paragraphs.join('\n\n'), { x: 0.8, y: 1.5, w: 11.5, h: 4.3, fontFace: 'Aptos', fontSize: 18, color: COLOR.ink, breakLine: false, fit: 'shrink', valign: 'top', margin: 0.06, paraSpaceAfter: 12 })
  } else {
    slide.addText('No overview paragraphs were supplied.', { x: 0.8, y: 1.5, w: 11.5, h: 1, fontFace: 'Aptos', fontSize: 18, color: COLOR.muted, margin: 0 })
  }

  if (payload.headings.length > 0 || payload.bullets.length > 0) {
    slide = presentation.addSlide()
    addHeader(slide, payload, 'Details')
    let y = 1.45
    for (const item of payload.headings) {
      slide.addText(item.text, { x: 0.8, y, w: 11.2, h: 0.35, fontFace: 'Aptos', fontSize: item.level === 1 ? 21 : 16, color: COLOR.purple, bold: true, margin: 0 })
      y += 0.42
    }
    if (payload.bullets.length > 0) {
      slide.addText(payload.bullets.map(item => ({ text: item, options: { bullet: { indent: 14 } } })), { x: 0.9, y, w: 10.9, h: 4.6, fontFace: 'Aptos', fontSize: 17, color: COLOR.ink, breakLine: false, fit: 'shrink', valign: 'top', margin: 0.05, paraSpaceAfter: 10 })
    }
  }

  if (payload.diagramSummary) {
    slide = presentation.addSlide()
    addHeader(slide, payload, payload.diagramSummary.title)
    if (payload.diagramSummary.summary) slide.addText(payload.diagramSummary.summary, { x: 0.8, y: 1.4, w: 11.3, h: 0.8, fontFace: 'Aptos', fontSize: 15, color: COLOR.muted, fit: 'shrink', margin: 0 })
    const nodes = payload.diagramSummary.nodes
    const nodeWidth = nodes.length > 0 ? Math.min(2.55, 10.8 / nodes.length) : 2.55
    nodes.forEach((node, index) => {
      const x = 0.8 + index * (nodeWidth + 0.22)
      slide.addShape(presentation.ShapeType.roundRect, { x, y: 2.65, w: nodeWidth, h: 0.9, rectRadius: 0.05, fill: { color: COLOR.light }, line: { color: 'C9B8EC', pt: 1.2 } })
      slide.addText(node, { x: x + 0.08, y: 2.9, w: nodeWidth - 0.16, h: 0.3, fontFace: 'Aptos', fontSize: 12, color: COLOR.ink, bold: true, align: 'center', fit: 'shrink', margin: 0 })
    })
    if (payload.diagramSummary.edges.length > 0) {
      slide.addText(payload.diagramSummary.edges.map(edge => `${edge.from} → ${edge.to}${edge.label ? ` (${edge.label})` : ''}`).join('\n'), { x: 0.9, y: 4.15, w: 10.9, h: 1.8, fontFace: 'Aptos', fontSize: 15, color: COLOR.ink, breakLine: false, fit: 'shrink', valign: 'top', margin: 0.05, paraSpaceAfter: 7 })
    }
  }

  const buffer = await presentation.write({ outputType: 'nodebuffer' })
  return new Uint8Array(buffer as Buffer)
}
